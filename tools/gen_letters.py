"""Generate the app's letters to trace from design/letters.json (synced from
the website repo, the single source for every product's letters).

    python3 tools/gen_letters.py

Writes designsystem/src/commonMain/kotlin/au/com/followmetherapy/design/letters/FmtLetters.kt:
each letter's width and strokes as compact strings ("x,y x,y …"), read once
when first used, so the same shapes are traced in the app, drawn in the
Design System and printed on the worksheets.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
L = json.loads((ROOT / "design/letters.json").read_text())
OUT = ROOT / "designsystem/src/commonMain/kotlin/au/com/followmetherapy/design/letters/FmtLetters.kt"


def kstr(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$") + '"'


def table(name, d):
    rows = []
    for k, g in d.items():
        strokes = ", ".join('"' + " ".join(f"{x:g},{y:g}" for x, y in st) + '"' for st in g["strokes"])
        rows.append(f"        {kstr(k)} to raw({g['width']}, {strokes}),")
    return f"    val {name}: Map<String, FmtGlyph> by lazy {{\n        mapOf(\n" + "\n".join("    " + r for r in rows) + "\n        )\n    }"


lines = L["lines"]
src = f'''// GENERATED by tools/gen_letters.py from design/letters.json. Don't edit:
// change tools/build_letters.py in the website repo, then sync.
package au.com.followmetherapy.design.letters

/** A letter or shape to trace: its width (the box is 100 high) and strokes in drawing order, each from its start. */
class FmtGlyph(val width: Float, val strokes: List<List<Pair<Float, Float>>>)

private fun raw(width: Int, vararg strokes: String) = FmtGlyph(width.toFloat(), strokes.map {{ s ->
    s.split(' ').map {{ p -> p.substringBefore(',').toFloat() to p.substringAfter(',').toFloat() }}
}})

/** Victorian foundation-style letters and the pre-writing shapes (tools/build_letters.py in the website repo). */
object FmtLetters {{
    const val TOP = {lines["top"]}f
    const val WAIST = {lines["waist"]}f
    const val BASE = {lines["base"]}f
    const val DESCENDER = {lines["descender"]}f
{table("lowercase", L["lowercase"])}
{table("capitals", L["capitals"])}
{table("shapes", L["shapes"])}
    /** A letter by itself ("a", "B") or a shape by name ("loops"). */
    fun glyph(name: String): FmtGlyph? = if (name.length > 1) shapes[name] else if (name == name.lowercase()) lowercase[name] else capitals[name]
}}
'''
OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text(src)
print(f"wrote {OUT.relative_to(ROOT)} ({len(L['lowercase'])}+{len(L['capitals'])} letters, {len(L['shapes'])} shapes)")
