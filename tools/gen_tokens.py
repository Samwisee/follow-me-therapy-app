"""Generate the Kotlin design tokens from design/tokens.json.

    python3 tools/gen_tokens.py

design/tokens.json is a copy of the single source in the website repo
(Samwisee/follow-me-therapy, design/tokens.json). tools/sync_design.sh
takes the latest and runs this; so do CI and the hourly Design sync.

Writes designsystem/src/commonMain/kotlin/au/com/followmetherapy/design/tokens/FmtTokens.kt

On screens the semantic tokens (text-*, gutter, card-pad, grid-gap, stack,
group-gap, section-*) are fluid: they grow from their phone value at 360dp
wide to their laptop value at 1440dp, exactly as on the website. They are
emitted as Fluid(min, max) and resolved for the current window width by
FmtTheme. Everything else is a fixed value.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
T = json.loads((ROOT / "design/tokens.json").read_text())
OUT = ROOT / "designsystem/src/commonMain/kotlin/au/com/followmetherapy/design/tokens/FmtTokens.kt"


def items(group):
    return [(k, v) for k, v in T[group].items() if not k.startswith("$")]


def camel(name):
    parts = re.split(r"[-_.]", name)
    head, rest = parts[0], parts[1:]
    s = head + "".join(p[:1].upper() + p[1:] for p in rest)
    if s[:1].isdigit():
        s = "x" + s
    return s


def resolve(val, seen=()):
    if isinstance(val, str):
        m = re.fullmatch(r"\{([^}]+)\}", val)
        if m:
            g, k = m.group(1).split(".", 1)
            return resolve(T[g][k]["$value"], seen + (m.group(1),))
    return val


def px(v):
    return float(str(v).removesuffix("px"))


def num(f):
    s = f"{float(f):.4f}".rstrip("0").rstrip(".")
    return s if "." in s else s + ".0"


def kdoc(v):
    d = v.get("$description", "").replace("*/", "* /").strip()
    return f"    /** {d} */\n" if d else ""


def color_literal(hexv):
    h = hexv.lstrip("#")
    if len(h) == 3:
        h = "".join(c * 2 for c in h)
    a = "FF"
    if len(h) == 8:
        h, a = h[:6], h[6:]
    return f"Color(0x{a.upper()}{h.upper()})"


def fluid(v):
    fl = v.get("$extensions", {}).get("followmetherapy", {}).get("fluid")
    if fl:
        return px(fl["min"]), px(fl["max"])
    p = px(resolve(v["$value"]))
    return p, p


L = []
w = L.append
w("// GENERATED by tools/gen_tokens.py from design/tokens.json. Don't edit;")
w("// change the tokens in the website repo, sync, and regenerate.")
w("package au.com.followmetherapy.design.tokens")
w("")
w("import androidx.compose.animation.core.CubicBezierEasing")
w("import androidx.compose.ui.graphics.Color")
w("import androidx.compose.ui.unit.dp")
w("")

# Colours
w("/** Colours. Light theme only, like the website. */")
w("object FmtColors {")
for k, v in items("color"):
    w(kdoc(v).rstrip("\n")) if kdoc(v) else None
    w(f"    val {camel(k)} = {color_literal(resolve(v['$value']))}")
w("}")
w("")

# Fixed scales
def fixed(obj, group, prefix="", doc=""):
    w(f"/** {doc} */")
    w(f"object {obj} {{")
    for k, v in items(group):
        val = resolve(v["$value"])
        if kdoc(v):
            w(kdoc(v).rstrip("\n"))
        name = ("s" + k) if (group == "space" and k[0].isdigit()) else camel(prefix + k)
        w(f"    val {name} = {num(px(val))}.dp")
    w("}")
    w("")

fixed("FmtSpace", "space", "", "The spacing scale. Physical: 1dp = 1 CSS px = 1/96 inch.")
# space keys: hair, 1..30 -> hair, s1..s30
fixed("FmtSize", "size", "", "Component sizes: targets, icons, tiles, buttons.")
fixed("FmtRadius", "radius", "", "Corner radii. Corners nest: container = inner + padding + outline.")
fixed("FmtBorder", "border", "", "Outline and focus-ring widths.")
fixed("FmtBreakpoint", "breakpoint", "", "Layout breakpoints (window width; short/shorter are heights).")

# Fluid semantic tokens
w("/** A value that grows linearly from [min] at 360dp wide to [max] at 1440dp. */")
w("data class Fluid(val min: Float, val max: Float) {")
w("    fun at(widthDp: Float): Float {")
w("        val t = ((widthDp - FLUID_FROM) / (FLUID_TO - FLUID_FROM)).coerceIn(0f, 1f)")
w("        return min + (max - min) * t")
w("    }")
w("    companion object {")
w("        const val FLUID_FROM = 360f")
w("        const val FLUID_TO = 1440f")
w("    }")
w("}")
w("")
w("/** Text sizes in sp, fluid on screens. */")
w("object FmtText {")
for k, v in items("text"):
    lo, hi = fluid(v)
    if kdoc(v):
        w(kdoc(v).rstrip("\n"))
    w(f"    val {camel('t' + k) if k[0].isdigit() else camel(k)} = Fluid({num(lo)}f, {num(hi)}f)")
w("}")
w("")
LAYOUT_NAMES = {"section": "sectionSpace", "card": "cardPad", "grid": "gridGap", "group": "groupGap"}
w("/** Layout rhythm in dp. The fluid ones grow with the window; the rest are fixed. */")
w("object FmtLayout {")
for k, v in items("layout"):
    lo, hi = fluid(v)
    if kdoc(v):
        w(kdoc(v).rstrip("\n"))
    w(f"    val {LAYOUT_NAMES.get(k, camel(k))} = Fluid({num(lo)}f, {num(hi)}f)")
w("}")
w("")

# Type
w("/** Line heights (multipliers) and letter spacing (em). */")
w("object FmtLeading {")
for k, v in items("leading"):
    w(f"    const val {camel(k)} = {num(resolve(v['$value']))}f")
w("}")
w("")
w("object FmtTracking {")
for k, v in items("tracking"):
    w(f"    const val {camel(k)} = {num(float(str(resolve(v['$value'])).removesuffix('em')))}f // em")
w("}")
w("")
w("object FmtWeight {")
for k, v in items("weight"):
    if kdoc(v):
        w(kdoc(v).rstrip("\n"))
    w(f"    const val {camel(k)} = {int(resolve(v['$value']))}")
w("}")
w("")
w("/** Named text styles: family, size token, weight, line height, letter spacing. */")
w("enum class FmtFamily { Display, Body }")
w("data class FmtTypeToken(val family: FmtFamily, val size: Fluid, val weight: Int, val lineHeight: Float, val letterSpacingEm: Float = 0f)")
w("object FmtTypography {")
for k, v in items("typography"):
    if k.startswith("print"):
        continue
    val = v["$value"]
    fam = "FmtFamily.Display" if "display" in str(val["fontFamily"]) else "FmtFamily.Body"
    fs = val["fontSize"]
    m = re.fullmatch(r"\{text\.([^}]+)\}", str(fs))
    size = f"FmtText.{camel('t' + m.group(1)) if m.group(1)[0].isdigit() else camel(m.group(1))}" if m else f"Fluid({num(px(fs))}f, {num(px(fs))}f)"
    wt = int(resolve(val["fontWeight"]))
    lh = float(resolve(val["lineHeight"]))
    ls = val.get("letterSpacing")
    lsem = 0.0
    if ls:
        ls = str(ls)
        lsem = float(ls.removesuffix("em")) if ls.endswith("em") else px(ls) / px(fs if not m else T["text"][m.group(1)]["$value"])
    if kdoc(v):
        w(kdoc(v).rstrip("\n"))
    w(f"    val {camel(k)} = FmtTypeToken({fam}, {size}, {wt}, {num(lh)}f, {num(lsem)}f)")
w("}")
w("")

# Motion
w("/** Durations (ms) and easings. */")
w("object FmtMotion {")
for k, v in items("motion"):
    val = resolve(v["$value"])
    if isinstance(val, list):
        w(f"    val {camel(k)} = CubicBezierEasing({', '.join(num(x) + 'f' for x in val)})")
    else:
        w(f"    const val {camel('dur-' + k)} = {int(float(str(val).removesuffix('ms')))}")
w("}")
w("")

# Shadows
w("/** A soft shadow: y offset, blur radius, colour (already at its alpha). */")
w("data class FmtShadowToken(val y: Float, val blur: Float, val color: Color)")
w("object FmtShadow {")
COL = {k: resolve(v["$value"]) for k, v in items("color")}
for k, v in items("shadow"):
    val = resolve(v["$value"])
    m = re.fullmatch(r"\s*(-?[\d.]+)(?:px)?\s+(-?[\d.]+)px\s+([\d.]+)px\s+color-mix\(in srgb, var\(--([a-z-]+)\) ([\d.]+)%, transparent\)\s*", val)
    assert m, f"unparsed shadow {k}: {val}"
    y, blur, cname, pct = float(m.group(2)), float(m.group(3)), m.group(4), float(m.group(5))
    w(f"    val {camel(k)} = FmtShadowToken({num(y)}f, {num(blur)}f, FmtColors.{camel(cname)}.copy(alpha = {num(pct / 100)}f))")
w("}")

w("")

# Tones and component tokens: which role or value each part of a shared
# component takes (tokens.json › tone, component; design/components.json).
TONES = [k for k in T["tone"] if not k.startswith("$")]
ROLES = [k for k in T["tone"][TONES[0]] if not k.startswith("$")]
def pascal(n):
    c = camel(n)
    return c[:1].upper() + c[1:]
def colour_ref(val):
    m = re.fullmatch(r"\{color\.([^}]+)\}", str(val))
    if m:
        return f"FmtColors.{camel(m.group(1))}"
    m = re.fullmatch(r"\{([^}]+)\}", str(val))
    if m:  # an alias to another token: resolve to its colour
        return colour_ref(resolve_path(m.group(1)))
    return color_literal(val)
def resolve_path(path):
    node = T
    for k in path.split("."):
        node = node[k]
    return node["$value"]
w("/** The four tones. Fixed meanings: purple = who it's for, teal = telehealth, sun = in person, pink = reports. */")
w("enum class FmtTone { " + ", ".join(pascal(t) for t in TONES) + " }")
w("")
w("/** The role a colour plays in a tone. Components pick a role, never a colour. */")
w("enum class FmtToneRole { " + ", ".join(pascal(r) for r in ROLES) + " }")
w("")
w("object FmtTones {")
w("    /** The colour that plays [role] in [tone]. */")
w("    fun color(tone: FmtTone, role: FmtToneRole): Color = when (tone) {")
for t in TONES:
    w(f"        FmtTone.{pascal(t)} -> when (role) {{")
    for r in ROLES:
        w(f"            FmtToneRole.{pascal(r)} -> {colour_ref(T['tone'][t][r]['$value'])}")
    w("        }")
w("    }")
w("}")
w("")
for comp, parts in T["component"].items():
    if comp.startswith("$"):
        continue
    if parts.get("$description"):
        w(f"/** {parts['$description'].replace('*/', '* /')} */")
    w(f"object Fmt{pascal(comp)}Tokens {{")
    for part, v in parts.items():
        if part.startswith("$"):
            continue
        if kdoc(v):
            w(kdoc(v).rstrip("\n"))
        name = camel(part)
        if v.get("$type") == "other":
            w(f"    fun {name}(tone: FmtTone): Color = FmtTones.color(tone, FmtToneRole.{pascal(v['$value'])})")
        elif v.get("$type") == "color":
            w(f"    val {name}: Color = {colour_ref(v['$value'])}")
        elif v.get("$type") == "dimension":
            w(f"    val {name} = {num(px(resolve(v['$value']) if not str(v['$value']).startswith('{') else resolve_path(str(v['$value'])[1:-1])))}.dp")
    w("}")
    w("")

# The web app's install manifest and page colours come from the tokens too:
# the bars' lilac (component.bar.fill) is the splash, the theme and the page edge.
def hex_of(path):
    v = resolve_path(path)
    while isinstance(v, str) and v.startswith("{"):
        v = resolve_path(v[1:-1])
    return v
BAR = hex_of("component.bar.fill")
