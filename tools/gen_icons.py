"""Generate the app's icons from design/icons.json (synced from the website repo,
the single source for every product's icons).

    pip install svgelements && python3 tools/gen_icons.py

Writes designsystem/src/commonMain/kotlin/au/com/followmetherapy/design/icons/FmtIcons.kt.
Shapes (circle, rect, ellipse) and transforms become plain paths, so the
icons are drawn exactly as on the website and in the worksheets.
"""
import io
import json
import re
from pathlib import Path

import svgelements as S

ROOT = Path(__file__).resolve().parent.parent
ICONS = json.loads((ROOT / "design/icons.json").read_text())["icons"]
OUT = ROOT / "designsystem/src/commonMain/kotlin/au/com/followmetherapy/design/icons/FmtIcons.kt"
STROKE = {24: "2.2f", 40: "2.6f"}


def camel(name):
    a, *b = name.split("-")
    return a + "".join(x[:1].upper() + x[1:] for x in b)


def paths(svg, grid):
    doc = S.SVG.parse(io.StringIO(f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {grid} {grid}">{svg}</svg>'), reify=True)
    out = []
    for e in doc.elements():
        if isinstance(e, S.Shape) and not isinstance(e, S.SVG):
            d = S.Path(e).d()
            if d:
                out.append(re.sub(r"(\d)\.(\d{3})\d+", r"\1.\2", d))
    return out


L = ["// GENERATED by tools/gen_icons.py from design/icons.json. Don't edit;",
     "// change the icons in the website repo, sync, and regenerate.",
     "package au.com.followmetherapy.design.icons",
     "",
     "import androidx.compose.ui.graphics.Color",
     "import androidx.compose.ui.graphics.SolidColor",
     "import androidx.compose.ui.graphics.StrokeCap",
     "import androidx.compose.ui.graphics.StrokeJoin",
     "import androidx.compose.ui.graphics.vector.ImageVector",
     "import androidx.compose.ui.graphics.vector.addPathNodes",
     "import androidx.compose.ui.unit.Dp",
     "",
     "/*",
     " * The design system's line icons (round caps and joins, no fill unless filled),",
     " * the same paths as the website and worksheets. 24×24 icons go beside words",
     " * (stroke 2.2); 40×40 icons go in an icon tile (stroke 2.6). Draw with FmtIcon.",
     " */",
     "private fun icon(name: String, grid: Float, stroke: Float, paths: List<String>, filled: Boolean = false): ImageVector {",
     "    val b = ImageVector.Builder(name = name, defaultWidth = Dp(grid), defaultHeight = Dp(grid), viewportWidth = grid, viewportHeight = grid)",
     "    for (d in paths) {",
     "        b.addPath(",
     "            pathData = addPathNodes(d),",
     "            fill = if (filled) SolidColor(Color.Black) else null,",
     "            stroke = if (filled) null else SolidColor(Color.Black),",
     "            strokeLineWidth = stroke,",
     "            strokeLineCap = StrokeCap.Round,",
     "            strokeLineJoin = StrokeJoin.Round,",
     "        )",
     "    }",
     "    return b.build()",
     "}",
     "",
     "object FmtIcons {"]
for name, ic in ICONS.items():
    g = ic["grid"]
    ps = ", ".join(f'"{d}"' for d in paths(ic["svg"], g))
    filled = ", filled = true" if ic.get("filled") else ""
    L.append(f'    val {camel(name)} = icon("{name}", {g}f, {STROKE[g]}, listOf({ps}){filled})')
L.append("}")
OUT.write_text("\n".join(L) + "\n")
print(f"wrote {OUT.relative_to(ROOT)} ({len(ICONS)} icons)")
